    private static string? GetWireValue<T>(T value)
        where T : struct, Enum
        => typeof(T)
            .GetField(value.ToString())
            .ShouldNotBeNull()
            .GetCustomAttribute<EnumMemberAttribute>()
            .ShouldNotBeNull()
            .Value;

