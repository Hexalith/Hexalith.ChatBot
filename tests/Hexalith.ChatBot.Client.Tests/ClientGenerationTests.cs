                cancellationToken: TestContext.Current.CancellationToken);

            SurfaceOrigin expected = Enum.Parse<SurfaceOrigin>(origin.ToString());
            transport.LastBody.ShouldNotBeNull().Origin.ShouldBe(expected);
        }
    }

